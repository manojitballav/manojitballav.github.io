#!/usr/bin/env python3
"""Build the self-hosted icon subset from Font Awesome Free.

The site uses ~55 icons, but the full Font Awesome webfont is ~155 KB. This
script keeps only the glyphs listed below and writes:

    fonts/icons/solid.woff2, regular.woff2, brands.woff2
    css/icons.css

To add an icon: add its Font Awesome name (without "fa-") to the right list,
then run

    pip install fonttools brotli
    python3 tools/build-icons.py

Icons named in JavaScript count too (e.g. the device-type tabs and the
travel-requests toast), so search the JS before removing anything.
"""

import os
import re
import sys
import tempfile
import urllib.request

from fontTools import subset
from fontTools.ttLib import TTFont

FA_VERSION = "6.5.1"
CDN = f"https://cdnjs.cloudflare.com/ajax/libs/font-awesome/{FA_VERSION}"

SOLID = [
    "arrow-left", "arrow-up-right-from-square", "ban", "box-open", "building",
    "camera", "car", "check", "check-circle", "chevron-down", "chevron-left",
    "chevron-right", "circle-exclamation", "circle-info", "circle-notch", "clock",
    "clock-rotate-left", "cloud-arrow-up", "coins", "compass", "filter", "gear",
    "handshake", "headphones", "layer-group", "location-dot", "magnifying-glass",
    "microchip", "mobile-screen", "moon", "paper-plane", "plane-departure", "play",
    "plus", "rss", "shield-halved", "sort", "sort-down", "sort-up", "spinner",
    "suitcase-rolling", "sun", "tablet-screen-button", "tag",
    "triangle-exclamation", "tv", "video", "volume-high", "weight-hanging", "wifi",
    "xmark",
]
REGULAR = ["envelope"]
BRANDS = ["facebook-f", "github", "instagram", "linkedin", "linkedin-in", "x-twitter"]

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FONT_DIR = os.path.join(ROOT, "fonts", "icons")
CSS_OUT = os.path.join(ROOT, "css", "icons.css")


def fetch(path, dest):
    with urllib.request.urlopen(f"{CDN}/{path}") as r, open(dest, "wb") as f:
        f.write(r.read())


def codepoints(css):
    """Map icon name -> codepoint from Font Awesome's all.css (aliases included)."""
    found = {}
    for selectors, cp in re.findall(r'([^{}]+)\{\s*content:\s*"\\([0-9a-f]+)";\s*\}', css):
        for name in re.findall(r"\.fa-([a-z0-9-]+):{1,2}before", selectors):
            found.setdefault(name, int(cp, 16))
    return found


def build_font(src, dest, cps):
    font = TTFont(src)
    opts = subset.Options()
    opts.flavor = "woff2"
    opts.layout_features = ["*"]
    opts.name_IDs = ["*"]
    opts.notdef_outline = True
    sub = subset.Subsetter(opts)
    sub.populate(unicodes=cps)
    sub.subset(font)
    font.flavor = "woff2"
    font.save(dest)
    return os.path.getsize(dest)


def main():
    with tempfile.TemporaryDirectory() as tmp:
        fetch("css/all.css", os.path.join(tmp, "all.css"))
        cp = codepoints(open(os.path.join(tmp, "all.css")).read())

        missing = [n for n in SOLID + REGULAR + BRANDS if n not in cp]
        if missing:
            sys.exit(f"Not in Font Awesome Free {FA_VERSION}: {', '.join(missing)}")

        os.makedirs(FONT_DIR, exist_ok=True)
        sizes = {}
        for style, src, names in [
            ("solid", "fa-solid-900.woff2", SOLID),
            ("regular", "fa-regular-400.woff2", REGULAR),
            ("brands", "fa-brands-400.woff2", BRANDS),
        ]:
            fetch(f"webfonts/{src}", os.path.join(tmp, src))
            sizes[style] = build_font(
                os.path.join(tmp, src),
                os.path.join(FONT_DIR, f"{style}.woff2"),
                [cp[n] for n in names],
            )

    rules = "\n".join(
        f'.fa-{n}::before {{ content: "\\{cp[n]:x}"; }}'
        for n in sorted(set(SOLID + REGULAR + BRANDS))
    )
    css = f"""/*!
 * Icon subset generated by tools/build-icons.py. Do not edit by hand.
 * Font Awesome Free {FA_VERSION} by @fontawesome - https://fontawesome.com
 * License - https://fontawesome.com/license/free (Icons: CC BY 4.0, Fonts: SIL OFL 1.1, Code: MIT License)
 * Copyright 2023 Fonticons, Inc.
 */
@font-face {{
  font-family: "Site Icons";
  font-style: normal;
  font-weight: 900;
  font-display: block;
  src: url("../fonts/icons/solid.woff2") format("woff2");
}}
@font-face {{
  font-family: "Site Icons";
  font-style: normal;
  font-weight: 400;
  font-display: block;
  src: url("../fonts/icons/regular.woff2") format("woff2");
}}
@font-face {{
  font-family: "Site Icons Brands";
  font-style: normal;
  font-weight: 400;
  font-display: block;
  src: url("../fonts/icons/brands.woff2") format("woff2");
}}

.fa-solid,
.fa-regular,
.fa-brands {{
  -moz-osx-font-smoothing: grayscale;
  -webkit-font-smoothing: antialiased;
  display: inline-block;
  font-style: normal;
  font-variant: normal;
  line-height: 1;
  text-rendering: auto;
}}
.fa-solid {{ font-family: "Site Icons"; font-weight: 900; }}
.fa-regular {{ font-family: "Site Icons"; font-weight: 400; }}
.fa-brands {{ font-family: "Site Icons Brands"; font-weight: 400; }}

.fa-spin {{ animation: fa-spin 2s linear infinite; }}
@keyframes fa-spin {{
  0% {{ transform: rotate(0deg); }}
  100% {{ transform: rotate(360deg); }}
}}
@media (prefers-reduced-motion: reduce) {{
  .fa-spin {{ animation-duration: 1ms; animation-iteration-count: 1; }}
}}

{rules}
"""
    with open(CSS_OUT, "w") as f:
        f.write(css)

    for style, size in sizes.items():
        print(f"fonts/icons/{style}.woff2  {size / 1024:.1f} KB")
    print(f"css/icons.css  {len(css) / 1024:.1f} KB, {len(set(SOLID + REGULAR + BRANDS))} icons")


if __name__ == "__main__":
    main()
